-- Limpiar tablas existentes si ya fueron creadas (safe reset)
DROP TABLE IF EXISTS actuacion CASCADE;
DROP TABLE IF EXISTS expediente CASCADE;
DROP TABLE IF EXISTS solicitud_documentacion CASCADE;
DROP TABLE IF EXISTS documento CASCADE;
DROP TABLE IF EXISTS representacion CASCADE;
DROP TABLE IF EXISTS ciudadano_organizacion CASCADE;
DROP TABLE IF EXISTS organizacion CASCADE;
DROP TABLE IF EXISTS ciudadanos_propiedades CASCADE;
DROP TABLE IF EXISTS propiedades CASCADE;
DROP TABLE IF EXISTS contacto_ciudadano_rel CASCADE;
DROP TABLE IF EXISTS contacto_ciudadano CASCADE;
DROP TABLE IF EXISTS relacion CASCADE;
DROP TABLE IF EXISTS credencial_ciudadano CASCADE;
DROP TABLE IF EXISTS credencial_empleado CASCADE;
DROP TABLE IF EXISTS cuenta_empleado CASCADE;
DROP TABLE IF EXISTS ciudadano CASCADE;

BEGIN;

-- ---------------------------------------------------------------- CIUDADANOS ---

-- Raiz de las personas fisicas.
CREATE TABLE ciudadano (
    ciudadano_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id     VARCHAR(255) NOT NULL,
    nombre           VARCHAR(255) NOT NULL,
    apellido         VARCHAR(255) NOT NULL,
    fecha_nacimiento DATE         NOT NULL,
    estado           VARCHAR(50)  NOT NULL DEFAULT 'ACTIVO',
    cuit             BIGINT       NOT NULL,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_ciudadano_dni       UNIQUE (documento_id),
    CONSTRAINT uk_ciudadano_cuit      UNIQUE (cuit),
    CONSTRAINT ck_ciudadano_estado    CHECK (estado IN ('ACTIVO', 'INACTIVO', 'FALLECIDO', 'BLOQUEADO'))
);

-- Credenciales de ciudadanos
CREATE TABLE credencial_ciudadano (
    ciudadano_id BIGINT       PRIMARY KEY,
    password     VARCHAR(100) NOT NULL,
    CONSTRAINT fk_credencial_ciudadano FOREIGN KEY (ciudadano_id) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE
);

-- Grupo familiar
CREATE TABLE relacion (
    relacion_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudadano_id_1       BIGINT       NOT NULL,
    ciudadano_id_2       BIGINT       NOT NULL,
    relacion_ciudadano_1 VARCHAR(100) NOT NULL,
    relacion_ciudadano_2 VARCHAR(100) NOT NULL,
    es_responsable       BOOLEAN      NOT NULL DEFAULT FALSE,
    creado_en            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_relacion_ciudadano_1 FOREIGN KEY (ciudadano_id_1) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_relacion_ciudadano_2 FOREIGN KEY (ciudadano_id_2) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT ck_relacion_distintos   CHECK (ciudadano_id_1 <> ciudadano_id_2),
    CONSTRAINT uk_relacion_par         UNIQUE (ciudadano_id_1, ciudadano_id_2)
);

-- ---------------------------------------------------------------- CONTACTO ---

CREATE TABLE contacto_ciudadano (
    contacto_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(50)  NOT NULL,
    valor         VARCHAR(255) NOT NULL,
    verificado    BOOLEAN      NOT NULL DEFAULT FALSE,
    verificado_en TIMESTAMPTZ,
    creado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_contacto_tipo CHECK (tipo IN ('EMAIL', 'TELEFONO'))
);

-- Tabla puente ciudadano <-> contacto
CREATE TABLE contacto_ciudadano_rel (
    ciudadano_id BIGINT NOT NULL,
    contacto_id  BIGINT NOT NULL,
    PRIMARY KEY (ciudadano_id, contacto_id),
    CONSTRAINT fk_contacto_rel_ciudadano FOREIGN KEY (ciudadano_id) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_contacto_rel_contacto  FOREIGN KEY (contacto_id)  REFERENCES contacto_ciudadano (contacto_id) ON DELETE CASCADE
);

-- --------------------------------------------------------------- DOMICILIOS ---

CREATE TABLE propiedades (
    propiedad_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(100) NOT NULL,
    calle        VARCHAR(255) NOT NULL,
    numero       VARCHAR(50)  NOT NULL,
    piso         VARCHAR(50),
    id_barrio    UUID,
    longitud     VARCHAR(50),
    latitud      VARCHAR(50)
);

-- Vinculo ciudadano-domicilio con vigencia
CREATE TABLE ciudadanos_propiedades (
    id_ciudadano  BIGINT  NOT NULL,
    id_propiedad  BIGINT  NOT NULL,
    vigente_desde DATE    NOT NULL DEFAULT CURRENT_DATE,
    vigente_hasta DATE,
    es_principal  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_ciudadano, id_propiedad),
    CONSTRAINT fk_cp_ciudadano FOREIGN KEY (id_ciudadano) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_cp_propiedad FOREIGN KEY (id_propiedad) REFERENCES propiedades (propiedad_id) ON DELETE CASCADE,
    CONSTRAINT ck_cp_vigencia  CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

-- A lo sumo un domicilio principal vigente por ciudadano
CREATE UNIQUE INDEX uk_cp_principal_vigente
    ON ciudadanos_propiedades (id_ciudadano)
    WHERE es_principal AND vigente_hasta IS NULL;

-- ----------------------------------------------------------- ORGANIZACIONES ---

CREATE TABLE organizacion (
    organizacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_id          VARCHAR(255) NOT NULL,
    razon_social    VARCHAR(255) NOT NULL,
    nombre          VARCHAR(255),
    tipo            VARCHAR(100) NOT NULL,
    estado          VARCHAR(50)  NOT NULL DEFAULT 'PENDIENTE',
    cuit            BIGINT       NOT NULL,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_organizacion_tax_id UNIQUE (tax_id),
    CONSTRAINT uk_organizacion_cuit   UNIQUE (cuit),
    CONSTRAINT ck_organizacion_estado CHECK (estado IN ('PENDIENTE', 'ACTIVA', 'INACTIVA', 'BLOQUEADA', 'RECHAZADA'))
);

-- Duenos/titulares
CREATE TABLE ciudadano_organizacion (
    id_ciudadano           BIGINT      NOT NULL,
    id_organizacion        BIGINT      NOT NULL,
    porcentaje_titularidad NUMERIC(5, 2),
    asociado_en            TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id_ciudadano, id_organizacion),
    CONSTRAINT fk_co_ciudadano    FOREIGN KEY (id_ciudadano)    REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_co_organizacion FOREIGN KEY (id_organizacion) REFERENCES organizacion (organizacion_id) ON DELETE CASCADE,
    CONSTRAINT ck_co_porcentaje   CHECK (porcentaje_titularidad IS NULL
                                         OR (porcentaje_titularidad > 0 AND porcentaje_titularidad <= 100))
);

-- Domicilios/propiedades de la organizacion.
CREATE TABLE organizaciones_propiedades (
    id_organizacion BIGINT NOT NULL,
    id_propiedad    BIGINT NOT NULL,
    vigente_desde   DATE    NOT NULL DEFAULT CURRENT_DATE,
    vigente_hasta   DATE,
    es_principal    BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id_organizacion, id_propiedad),
    CONSTRAINT fk_op_organizacion FOREIGN KEY (id_organizacion) REFERENCES organizacion (organizacion_id) ON DELETE CASCADE,
    CONSTRAINT fk_op_propiedad    FOREIGN KEY (id_propiedad)    REFERENCES propiedades (propiedad_id) ON DELETE CASCADE,
    CONSTRAINT ck_op_vigencia     CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_op_principal_vigente
    ON organizaciones_propiedades (id_organizacion)
    WHERE es_principal AND vigente_hasta IS NULL;


-- Poder para operar en nombre de una organizacion
CREATE TABLE representacion (
    representacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudadano_id      BIGINT       NOT NULL,
    organizacion_id   BIGINT       NOT NULL,
    alcance           VARCHAR(255) NOT NULL,
    desde             DATE         NOT NULL,
    hasta             DATE,
    estado            VARCHAR(50)  NOT NULL DEFAULT 'VIGENTE',
    CONSTRAINT fk_representacion_ciudadano    FOREIGN KEY (ciudadano_id)    REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_representacion_organizacion FOREIGN KEY (organizacion_id) REFERENCES organizacion (organizacion_id) ON DELETE CASCADE,
    CONSTRAINT ck_representacion_estado       CHECK (estado IN ('VIGENTE', 'VENCIDA', 'REVOCADA')),
    CONSTRAINT ck_representacion_fechas       CHECK (hasta IS NULL OR hasta >= desde)
);

-- Una sola representacion VIGENTE por par ciudadano-organizacion
CREATE UNIQUE INDEX uk_representacion_vigente
    ON representacion (ciudadano_id, organizacion_id)
    WHERE estado = 'VIGENTE';

-- ----------------------------------------------------------- DOCUMENTACION ---

CREATE TABLE documento (
    documento_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciudadano_id         BIGINT       NOT NULL,
    tipo_documento       VARCHAR(100) NOT NULL,
    version              INTEGER      NOT NULL DEFAULT 1,
    vigencia_hasta       DATE,
    cargado_por          VARCHAR(255) NOT NULL,
    validado_por         VARCHAR(255),
    url_archivo          VARCHAR(500),
    resultado_validacion VARCHAR(50)  NOT NULL DEFAULT 'PENDIENTE',
    fecha_validacion     TIMESTAMPTZ,
    fecha_creacion       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_documento_ciudadano FOREIGN KEY (ciudadano_id) REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT ck_documento_version   CHECK (version >= 1),
    CONSTRAINT ck_documento_resultado CHECK (resultado_validacion IN ('PENDIENTE', 'VALIDADO', 'RECHAZADO'))
);

-- Pedido de documentacion faltante
CREATE TABLE solicitud_documentacion (
    solicitud_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titular_id     BIGINT       NOT NULL,
    tipo_documento VARCHAR(100) NOT NULL,
    plazo          DATE         NOT NULL,
    estado         VARCHAR(50)  NOT NULL DEFAULT 'PENDIENTE',
    origen         VARCHAR(100) NOT NULL DEFAULT 'INTERNA',
    documento_id   BIGINT,
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_solicitud_titular   FOREIGN KEY (titular_id)   REFERENCES ciudadano (ciudadano_id) ON DELETE CASCADE,
    CONSTRAINT fk_solicitud_documento FOREIGN KEY (documento_id) REFERENCES documento (documento_id),
    CONSTRAINT ck_solicitud_estado    CHECK (estado IN ('PENDIENTE', 'CUMPLIDA', 'VENCIDA')),
    CONSTRAINT ck_solicitud_origen    CHECK (origen IN ('INTERNA', 'EVENTO')),
    CONSTRAINT ck_solicitud_cumplida  CHECK (estado <> 'CUMPLIDA' OR documento_id IS NOT NULL)
);

-- ------------------------------------------------------------- EXPEDIENTES ---

CREATE TABLE expediente (
    expediente_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero          VARCHAR(100) NOT NULL,
    ciudadano_id    BIGINT       NOT NULL,
    area_iniciadora VARCHAR(255) NOT NULL,
    estado          VARCHAR(50)  NOT NULL DEFAULT 'INICIADO',
    caratula        VARCHAR(255) NOT NULL,
    fecha_inicio    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_expediente_ciudadano FOREIGN KEY (ciudadano_id) REFERENCES ciudadano (ciudadano_id),
    CONSTRAINT uk_expediente_numero    UNIQUE (numero),
    CONSTRAINT ck_expediente_estado    CHECK (estado IN ('INICIADO', 'EN_TRAMITE', 'RESUELTO', 'ARCHIVADO'))
);

CREATE TABLE actuacion (
    expediente_id BIGINT       NOT NULL,
    actuacion_id  BIGINT       NOT NULL,
    tipo          VARCHAR(100) NOT NULL,
    modulo_origen VARCHAR(100) NOT NULL,
    descripcion   TEXT         NOT NULL,
    fecha         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    adjuntos      TEXT,
    PRIMARY KEY (expediente_id, actuacion_id),
    CONSTRAINT fk_actuacion_expediente FOREIGN KEY (expediente_id) REFERENCES expediente (expediente_id) ON DELETE CASCADE
);

-- --------------------------------------------------------------- EMPLEADOS ---

CREATE TABLE cuenta_empleado (
    empleado_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail              VARCHAR(200) NOT NULL,
    nombre_empleado   VARCHAR(25)  NOT NULL,
    apellido_empleado VARCHAR(25)  NOT NULL,
    rol               VARCHAR(50)  NOT NULL,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_empleado_mail UNIQUE (mail),
    CONSTRAINT ck_empleado_rol  CHECK (rol IN ('MESA_ENTRADAS', 'ADMINISTRATIVO', 'RESPONSABLE_AREA', 'AUDITOR'))
);

CREATE TABLE credencial_empleado (
    empleado_id BIGINT       PRIMARY KEY,
    password    VARCHAR(100) NOT NULL,
    CONSTRAINT fk_credencial_empleado FOREIGN KEY (empleado_id) REFERENCES cuenta_empleado (empleado_id) ON DELETE CASCADE
);

-- ------------------------------------------------------------------ INDICES ---

CREATE INDEX ix_ciudadano_apellido ON ciudadano (lower(apellido));
CREATE INDEX ix_ciudadano_nombre   ON ciudadano (lower(nombre));
CREATE INDEX ix_ciudadano_estado   ON ciudadano (estado);

CREATE INDEX ix_contacto_valor ON contacto_ciudadano (lower(valor));

CREATE INDEX ix_cp_ciudadano     ON ciudadanos_propiedades (id_ciudadano);
CREATE INDEX ix_propiedad_barrio ON propiedades (id_barrio);

CREATE INDEX ix_representacion_ciudadano    ON representacion (ciudadano_id);
CREATE INDEX ix_representacion_organizacion ON representacion (organizacion_id);

CREATE INDEX ix_documento_ciudadano ON documento (ciudadano_id, tipo_documento);
CREATE INDEX ix_solicitud_titular   ON solicitud_documentacion (titular_id, estado);

CREATE INDEX ix_expediente_ciudadano ON expediente (ciudadano_id);
CREATE INDEX ix_expediente_estado    ON expediente (estado);

-- ------------------------------------------------------------------ EVENTOS ---

CREATE TABLE events (
    event_id        VARCHAR(36)  PRIMARY KEY,
    aggregate_type  VARCHAR(100) NOT NULL,
    aggregate_id    VARCHAR(100) NOT NULL,
    event_type      VARCHAR(100) NOT NULL,
    payload         TEXT         NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    type            VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_events_type CHECK (lower(type) IN ('emitido', 'recibido'))
);

CREATE INDEX ix_events_type ON events (type);
CREATE INDEX ix_events_event_type ON events (event_type);
CREATE INDEX ix_events_aggregate ON events (aggregate_type, aggregate_id);

COMMIT;

